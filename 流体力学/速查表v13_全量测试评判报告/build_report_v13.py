def estimate_v13(rule: dict, question_text: str, group: str, max_score: float) -> tuple[float, str, str]:
    q = question_text
    ratio = float(rule["base"])
    basis = [f"主题命中“{rule['topic']}”，v13 基础过程覆盖约 {round(rule['base']*100)}%。"]
    if base.re.search(r"(简述|定义|为什么|说明|意义|差异|特点|是什么)", q):
        if rule["topic"] not in ["水波/水击/课程概念缺口", "概念简答/定义解释"]:
            ratio -= 0.04
            basis.append("题型偏概念简答；v13 有 M16/M18/M20/M23 定位和骨架，但非对应专栏仍扣少量组织分。")
    if base.re.search(r"(推导|证明|π|Pi|量纲|动量积分|排挤厚度|动量损失厚度|Karman|卡门)", q, base.re.I):
        ratio -= 0.05
        basis.append("题目要求推导或定义积分；v13 有 M20/M24/M25/M26 骨架，但完整教材推导仍扣少量严谨性分。")
    if base.re.search(r"(查|图|表|Moody|Colebrook|PM|斜激波|面积|马赫|阻力系数)", q, base.re.I):
        ratio -= 0.04
        basis.append("仍依赖教材图表或读图；v13 有小查表、查表动作、题号入口和收口模板，但不是完整数值表。")
    if "（题干在原文件中为图片" in q or "文字抽取不足" in q:
        ratio = min(ratio, 0.38)
        basis.append("题干主要是图片索引，未 OCR 到完整条件；v13 的 2007 扫描卷入口能保模型分，但无法保证数值答案。")
    ratio = max(0.0, min(0.96, ratio))
    est = round(max_score * ratio, 1)
    confidence = "中"
    if "文字抽取不足" in q:
        confidence = "低"
    elif len(q) > 80 and len(rule["paths"]) >= 3:
        confidence = "中高"
    return est, "；".join(basis), confidence


